import React from 'react';
import {createRoot} from 'react-dom/client';
import {MarketKeywordFactsReport,MarketKeywordRevisionReport} from '../../../app/market-keyword-report';
import type {MarketKeywordRevisionCatalog} from '../../../shared/market-keyword-revision-contracts';
import type {MarketKeywordRuleReport} from '../../../shared/market-keyword-rule-report-contracts';
import '../../../app/globals.css';
import '../../../app/market-ui-reference.css';
import '../../../app/market-research.css';
const rulesOnly=new URLSearchParams(location.search).has('rulesOnly');
const payload:MarketKeywordRevisionCatalog|{catalog:MarketKeywordRevisionCatalog;ruleReport:MarketKeywordRuleReport}=await fetch(rulesOnly?'/__keyword_rule_fixture':'/__keyword_report_fixture').then(r=>r.json());
const catalog=rulesOnly?(payload as {catalog:MarketKeywordRevisionCatalog}).catalog:payload as MarketKeywordRevisionCatalog;
const ruleReport=rulesOnly?(payload as {ruleReport:MarketKeywordRuleReport}).ruleReport:undefined;
createRoot(document.getElementById('root')!).render(<main className="market-ui-reference market-research-section"><MarketKeywordFactsReport facts={catalog.facts} ruleReport={ruleReport} semanticSkipped={rulesOnly}/><MarketKeywordRevisionReport catalog={catalog} ruleReport={ruleReport} semanticSkipped={rulesOnly}/></main>);
