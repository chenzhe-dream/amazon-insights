import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { shapePageRun, shapeRevision, shapeStructureRevision, shapeRequestBoundRevision, shapeRunId, shapeRevisionId } from './helpers/market-shape-page-fixture';
test('shape page requires human confirmation, saves a numeric version and reopens without recollection', { timeout: 60000 }, async (t) => {
    const server = await createServer({ configFile: false, cacheDir: 'test-results/shape-page-vite', define: { 'process.env': '{}' }, plugins: [react()], server: { host: '127.0.0.1', port: 0, hmr: false, forwardConsole: false } });
    await server.listen();
    const browser = await chromium.launch({ headless: true });
    t.after(async () => { await browser.close(); await server.close(); });
    const origin = server.resolvedUrls!.local[0].replace(/\/$/, '');
    const page = await browser.newPage({ viewport: { width: 1400, height: 1100 } });
    page.setDefaultTimeout(5000);
    const errors: string[] = [], writes: unknown[] = [];
    let current = shapePageRun(), readFailure = false;
    page.on('pageerror', e => errors.push(e.message));
    await page.route('**/*', async (route) => {
        const req = route.request(), url = new URL(req.url());
        if (url.origin !== origin)
            return route.abort();
        if (req.isNavigationRequest())
            return route.fulfill({ contentType: 'text/html', body: await server.transformIndexHtml('/', `<!doctype html><html><body style="margin:20px"><div id="root"></div><script type="module" src="/tests/agent/helpers/market-shape-browser-harness.tsx"></script></body></html>`) });
        if (!url.pathname.startsWith('/api/'))
            return route.continue();
        if (req.method() === 'POST') {
            assert.ok(url.pathname.endsWith('/shape-price/revisions'));
            const body = req.postDataJSON();
            writes.push(body);
            assert.deepEqual(body.assignments, [{ asin: 'B000000001', labelId: 'shelf' }]);
            assert.equal(body.expectedParentRevisionId, null);
            const revision = shapeRevision();
            current.run.latestRevision = revision;
            current.run.history = [{ revisionId: revision.revisionId, ordinal: 1, createdAt: revision.createdAt }];
            return route.fulfill({ status: 201, json: { revision } });
        }
        if (url.pathname.includes('/shape-price/revisions/'))
            return route.fulfill({ json: { revision: shapeRevision() } });
        if (url.pathname.endsWith('/shape-price'))
            return route.fulfill(readFailure ? { status: 503, json: {} } : { json: current });
        return route.fulfill({ status: 404, json: {} });
    });
    await page.goto(`${origin}/?shapeRun=${shapeRunId}`);
    const assignment = page.getByLabel('B000000001 人工形态');
    await assignment.waitFor();
    assert.equal(await assignment.inputValue(), '');
    await page.getByText('模型建议：层架式', { exact: true }).waitFor();
    assert.equal(writes.length, 0);
    await assignment.selectOption('shelf');
    await page.getByRole('button', { name: '确认并重新计算' }).click();
    const report = page.getByRole('region', { name: '形态价格带版本报告' });
    await report.waitFor();
    await report.getByText('可比销量：0', { exact: true }).waitFor();
    assert.match(await report.innerText(), /参考价/);
    assert.equal(writes.length, 1);
    await mkdir('test-results/market-shape-page', { recursive: true });
    await page.screenshot({ path: 'test-results/market-shape-page/desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
    await page.screenshot({ path: 'test-results/market-shape-page/mobile.png', fullPage: true });
    await page.reload();
    await report.waitFor();
    assert.equal(writes.length, 1);
    assert.equal(await page.getByLabel('B000000001 人工形态').inputValue(), 'shelf');
    current.run.latestRevision!.labels[0].label = '人工分类修订';
    await page.getByRole('button', { name: '刷新形态状态' }).click();
    await page.getByRole('option', { name: '人工分类修订', exact: true }).waitFor({ state: 'attached' });
    await page.getByText('模型建议：层架式', { exact: true }).waitFor();
    readFailure = true;
    await page.getByRole('button', { name: '刷新形态状态' }).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByRole('button', { name: '确认并重新计算' }).isDisabled(), true);
    await report.waitFor();
    readFailure = false;
    await page.getByRole('button', { name: '刷新形态状态' }).click();
    await page.getByRole('alert').waitFor({ state: 'detached' });
    await page.getByLabel('形态报告版本').selectOption(shapeRevisionId);
    await report.waitFor();
    current.run.latestRevision=shapeStructureRevision();
    current.run.history=[{revisionId:current.run.latestRevision.revisionId,ordinal:2,createdAt:current.run.latestRevision.createdAt},{revisionId:shapeRevisionId,ordinal:1,createdAt:shapeRevision().createdAt}];
    await page.getByLabel('形态报告版本').selectOption('latest');
    await page.getByRole('button',{name:'刷新形态状态'}).click();
    const structure=page.getByRole('region',{name:'品牌与上架年龄结构'});
    await structure.waitFor();
    await page.setViewportSize({width:1400,height:1100});
    const brands=structure.getByRole('region',{name:'品牌与价格带交叉表'});
    assert.match(await brands.innerText(),/Fixture/);
    assert.match(await brands.innerText(),/未知[\s\S]*0 \/ 0/);
    await structure.getByLabel('结构比较范围').selectOption('shape:shelf');
    await structure.getByText('品牌及上架日期来源').click();
    assert.match(await structure.innerText(),/上架日期晚于研究结束月/);
    assert.match(await structure.innerText(),/2026-09-01/);
    assert.match(await structure.innerText(),/data.*shelfDate/);
    await page.screenshot({path:'test-results/market-shape-page/structure-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
    await page.screenshot({path:'test-results/market-shape-page/structure-mobile.png',fullPage:true});
    await page.getByLabel('形态报告版本').selectOption(shapeRevisionId);
    await page.getByText('此历史版本未保存品牌与上架年龄结构。',{exact:true}).waitFor();
    assert.equal(await page.getByRole('region',{name:'品牌与上架年龄结构'}).count(),0);
    await page.getByLabel('形态报告版本').selectOption('latest');
    await page.reload();
    await structure.waitFor();
    assert.equal(writes.length,1,'viewing structure and history cannot recollect or rewrite');
    current.run.latestRevision=shapeRequestBoundRevision();current.run.sourcePolicy=current.run.latestRevision.sourcePolicy;
    current.run.history.unshift({revisionId:current.run.latestRevision.revisionId,ordinal:3,createdAt:current.run.latestRevision.createdAt});
    await page.getByRole('button',{name:'刷新形态状态'}).click();
    const policy=report.getByRole('note',{name:'商品数据依据'});await policy.waitFor();
    assert.match(await policy.innerText(),/请求范围绑定/);assert.match(await policy.innerText(),/供应商站点定义/);
    await page.setViewportSize({width:1400,height:1100});
    await policy.scrollIntoViewIfNeeded();await page.screenshot({path:'test-results/market-shape-page/source-policy-desktop.png'});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
    await policy.scrollIntoViewIfNeeded();await page.screenshot({path:'test-results/market-shape-page/source-policy-mobile.png'});
    await page.getByLabel('起始月',{exact:true}).fill('2020-01');
    await page.getByRole('button',{name:'采集商品并生成形态建议'}).click();
    await page.getByRole('alert').filter({hasText:'24'}).waitFor();
    assert.equal(writes.length,1,'unsupported month is rejected before any study or source write');
    assert.deepEqual(errors, []);
});
