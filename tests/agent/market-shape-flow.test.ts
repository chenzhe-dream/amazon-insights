import {MarketShapeSuggestionInputSchema} from '../../shared/market-semantic-contracts';
import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { startPostgresTestContainer } from './helpers/postgres-test-container';
import { runPostgresMigrations } from '../../server/db/postgres/migrations';
import { createMarketSemanticFixture } from './helpers/market-semantic-fixture';
import { createMarketModelRuntime } from '../../server/runtime/market-model-runtime';
import { loadVocPositioningRuntimeConfig } from '../../server/config';
import { marketShapeFlowInitialSteps, inspectMarketShapeContinuation } from '../../server/domain/market-research/shape-price-flow';
import { PostgresMarketShapePriceRevisionStore } from '../../server/db/postgres/market-shape-price-revision-store';
import { MarketModuleService } from '../../server/services/market-module-service';
import type { RemoteMcpConnector } from '../../server/connectors/connector-contract';
import { ConnectorError } from '../../server/connectors/connector-contract';
import Fastify from 'fastify';
import { registerMarketModuleRoutes } from '../../server/routes/market-modules';
import type { OpenAIProviderOptions } from '../../server/runtime/openai-provider';
test('shape flow freezes members, collects their history and audits suggestions without accepting them as manual choices', { timeout: 120000 }, async (t) => {
    const pg = await startPostgresTestContainer();
    t.after(() => pg.close());
    await runPostgresMigrations(pg.pool);
    const f = await createMarketSemanticFixture(pg.pool);
    await f.stores.steps.cancelModuleRun({ actor: f.actor, moduleRunId: f.subject.moduleRunId, idempotencyKey: randomUUID() });
    const calls: string[] = [];
    let modelCalls = 0, failHistory = false, emitEcho=true;
    const connector: RemoteMcpConnector = { id: 'sellerSprite', probe: async () => { throw Error('unused'); }, execute: async (r) => {
            const q = r.input.request as {month:string};
            calls.push(q.month);
            if (failHistory && q.month === '202607')
                throw new ConnectorError('sellerSprite', 'upstream-permanent', false);
            return { data: { code: 'OK', ...(emitEcho?{marketplace: 'US', currency: 'USD', nodeIdPath: f.scope.nodeIdPath, month: q.month}:{}), data: [{ asin: 'B000000001', title: 'Shelf lamp', brand: 'Fixture', price: 20, totalUnits: 10, totalRevenue: 200, ranking: 1, rating: 4, ratings: 10, sellerName: 'Fixture', sellerType: 'FBA', shelfDate: '2025-01-01', imageUrl:'https://m.media-amazon.com/images/I/fixture.jpg' }] }, source: { connectorId: 'sellerSprite', operation: r.operation, fetchedAt: new Date().toISOString(), attemptCount: 1 } };
        } };
    // A known tokenizer keeps this legacy synthetic model-path fixture inside
    // the task's 8k input admission; no external model call is made.
    const base = loadVocPositioningRuntimeConfig({ OPENAI_API_KEY: 'synthetic-key', AGENT_VOC_MODEL: 'gpt-4o', AGENT_VOC_ESTIMATED_INPUT_TOKENS: '12000', AGENT_VOC_MAX_OUTPUT_TOKENS: '4000', AGENT_VOC_TIMEOUT_MS: '60000', AGENT_VOC_INPUT_USD_PER_MILLION_TOKENS: '1', AGENT_VOC_OUTPUT_USD_PER_MILLION_TOKENS: '2', AGENT_VOC_CALL_MAX_TOKENS: '1000000', AGENT_VOC_CALL_MAX_COST_MICROS: '10000000', AGENT_VOC_RUN_MAX_TOKENS: '1000000', AGENT_VOC_RUN_MAX_COST_MICROS: '10000000', AGENT_VOC_DAILY_MAX_TOKENS: '1000000', AGENT_VOC_DAILY_MAX_COST_MICROS: '10000000', AGENT_VOC_WORKER_OWNER_ID: 'synthetic-shape-worker' });
    const client = { responses: { create: async (body: {input:string}) => {
                modelCalls++;
                const input = MarketShapeSuggestionInputSchema.parse(JSON.parse(body.input));
                assert.equal(input.task, 'market-product-shape-suggestion');
                const output = { schemaVersion: input.schemaVersion, task: input.task, batchId: input.batchId, inputDigest: input.inputDigest, products: input.products.map(p => { assert.ok(p.title.state==='known'); return ({ productId: p.productId, decision: { status: 'supported', candidates: [{ labelId: 'shelf', evidence: [{ refId: p.title.value.refId, start: 0, end: 5, quote: 'Shelf' }] }], requiresManualConfirmation: true } }); }) };
                return { id: 'synthetic-shape-' + modelCalls, status: 'completed', usage: { input_tokens: 300, output_tokens: 150, total_tokens: 450 }, output: [{ type: 'message', role: 'assistant', status: 'completed', content: [{ type: 'output_text', text: JSON.stringify(output) }] }] };
            } } } as unknown as OpenAIProviderOptions['client'];
    const create = () => createMarketModelRuntime(f.context, base, { client, connectors: { sellerSprite: connector, sorftime: connector } });
    let runtime = await create();
    t.after(() => runtime.stop());
    const labels = [{ labelId: 'shelf', label: '层架式', definition: '标题明确带层架的灯' }];
    const request = { actor: f.actor, scope: f.scope, moduleKind: 'shape-price' as const, params: { flow: 'market-shape-price-flow/v1', poolSize: 100, newProductMonths: 6, catalog: { task: 'market-product-shape-suggestion', taxonomyVersion: 'test-shapes/v1', allowedLabels: labels } }, versions: { source: 'market-source-handlers/v1', rule: 'market-shape-price-catalog/v1', mapping: 'test-shapes/v1', planner: 'market-shape-price-flow/v1', model: runtime.modelAlias, prompt: runtime.promptVersion, configuration: runtime.configurationVersion }, collectionRevision: 'initial/v1', idempotencyKey: randomUUID() };
    const { run } = await f.stores.steps.createModuleRun({ ...request, initialSteps: marketShapeFlowInitialSteps(request) });
    await runtime.tick();
    await runtime.stop();
    runtime = await create();
    for (let i = 0; i < 30 && await runtime.tick(); i++) { }
    const view = (await f.stores.steps.findModuleRun({ actor: f.actor, moduleRunId: run.id }))!;
    assert.ok(view.steps.every(s => s.status === 'succeeded'), JSON.stringify(view.attempts));
    assert.deepEqual(calls, ['202608', '202607']);
    assert.equal(modelCalls, 1);
    const projection = view.steps.find(s => s.kind === 'prepare-members' && (s.input as { phase?: string }).phase !== 'select-shape-members')!;
    const projectionOutput = view.attempts.find(a => a.id === projection.latestAttemptId)!.output as { ruleBaseline: { module: string; metrics: { key: string; value: number | null; missingReason: string | null }[] } };
    assert.equal(projectionOutput.ruleBaseline.module, 'shape-price');
    assert.equal(projectionOutput.ruleBaseline.metrics.find(metric => metric.key === 'totalUnits')?.value, 10);
    assert.equal(projectionOutput.ruleBaseline.metrics.find(metric => metric.key === 'margin')?.missingReason, 'cost inputs are not collected');
    assert.equal(view.run.status, 'partial');
    assert.equal(inspectMarketShapeContinuation(view, new Date().toISOString()).children.length, 0);
    const service = new MarketModuleService({ context: f.context, modelIdentity: () => ({ configurationVersion: runtime.configurationVersion, promptVersion: runtime.promptVersion }) });
    const publicView = await service.findShapes(f.actor, run.id);
    assert.equal(publicView.run.source!.products[0].title, 'Shelf lamp');
    const metadata=publicView.run.source!.products[0].metadata!;
    assert.equal(metadata.imageUrl?.value,'https://m.media-amazon.com/images/I/fixture.jpg');
    assert.equal(publicView.run.source!.summary!.totalUnits,20);
    assert.deepEqual(publicView.run.source!.summary!.monthly.map(m=>m.totalUnits),[10,10]);
    assert.equal(metadata.revenue.value,200);
    assert.equal(metadata.rating.value,4);
    assert.equal(metadata.ratingCount.value,10);
    assert.equal(metadata.sellerName.value,'Fixture');
    assert.equal(metadata.sellerType.value,'FBA');
    assert.equal(metadata.listedAt.value,'2025-01-01');
    assert.deepEqual(metadata.revenue.evidence.payloadPath,['data',0,'totalRevenue']);
    assert.equal(metadata.revenue.evidence.inputSnapshotId,publicView.run.source!.referenceSnapshotId);
    assert.equal(publicView.run.suggestions.status, 'complete');
    assert.equal(publicView.run.suggestions.items[0].decision.status, 'supported');
    assert.equal(publicView.run.latestRevision, null);
    const revisions = new PostgresMarketShapePriceRevisionStore(f.context);
    assert.equal(await revisions.find({ actor: f.actor, moduleRunId: run.id }), null);
    const source = (month: string) => view.attempts.find(a => view.steps.some(s => s.id === a.stepId && s.kind === 'collect-product-month' && (s.input as {month:string}).month === month))!;
    const saved = await revisions.save({ actor: f.actor, moduleRunId: run.id, idempotencyKey: randomUUID(), request: { referenceAttemptId: source('2026-08').id, historyAttemptIds: [source('2026-07').id], expectedParentRevisionId: null, selectedAsins: ['B000000001'], taxonomyVersion: 'test-shapes/v1', labels, assignments: [], bands: [{ id: 'all', minInclusive: 0, maxExclusive: null }] } });
    assert.equal(saved.catalog.products[0].shape, null);
    assert.equal(saved.catalog.products[0].classificationBasis, 'unclassified');
    assert.equal(saved.catalog.analysis.totals.totalUnits, 20);
    const report = await service.shapeRevision(f.actor, run.id, saved.catalog.revision.revisionId);
    assert.equal(report.revision.totalUnits, 20);
    assert.equal(report.revision.groups[0].labelId, null);
    assert.equal(report.revision.structure, undefined, 'legacy v1 report must not gain new structure');
    assert.equal((await service.findShapes(f.actor, run.id)).run.history.length, 1);
    await runtime.stop();
    runtime = await create();
    assert.equal(await runtime.tick(), false);
    assert.equal(modelCalls, 1);
    assert.equal(calls.length, 2);
    await t.test('HTTP reads are scoped and explicit revision writes keep the saved version', async () => {
        const callsBeforeReads={source:calls.length,model:modelCalls};
        const app = Fastify();
        t.after(() => app.close());
        app.addHook('preHandler', async (req) => { if (req.headers['x-test-auth'] === 'yes')
            req.authPrincipal = { kind: 'user', ...f.actor } as NonNullable<typeof req.authPrincipal>; });
        registerMarketModuleRoutes(app, service);
        const url = `/v1/market-analysis/runs/${run.id}/shape-price`;
        assert.equal((await app.inject({ url })).statusCode, 401);
        const publicRead=await app.inject({ url, headers: { 'x-test-auth': 'yes' } });
        assert.equal(publicRead.statusCode, 200);
        assert.equal(publicRead.json().run.source.products[0].metadata.revenue.value,200);
        assert.equal(publicRead.json().run.latestRevision.periodProjection.basisCatalogId,saved.catalog.catalogId);
        assert.equal((await app.inject({ url: `/v1/market-analysis/runs/${randomUUID()}/shape-price`, headers: { 'x-test-auth': 'yes' } })).statusCode, 404);
        const revise = { referenceAttemptId: source('2026-08').id, historyAttemptIds: [source('2026-07').id], expectedParentRevisionId: saved.catalog.revision.revisionId, selectedAsins: ['B000000001'], taxonomyVersion: 'test-shapes/v1', labels, assignments: [{ asin: 'B000000001', labelId: 'shelf' }], bands: [{ id: 'all', minInclusive: 0, maxExclusive: null }] }, key = randomUUID();
        const send = () => app.inject({ method: 'POST', url: url + '/revisions', headers: { 'x-test-auth': 'yes', 'idempotency-key': key }, payload: revise });
        const first = await send();
        assert.equal(first.statusCode, 201, first.body);
        assert.equal((await send()).statusCode, 200);
        assert.equal(first.json().revision.groups[0].labelId, 'shelf');
        const old = await app.inject({ url: url + '/revisions/' + encodeURIComponent(saved.catalog.revision.revisionId), headers: { 'x-test-auth': 'yes' } });
        assert.equal(old.statusCode, 200);
        assert.equal(old.json().revision.groups[0].labelId, null);
        assert.equal(old.json().revision.periodProjection.basisCatalogId,saved.catalog.catalogId);
        assert.deepEqual({source:calls.length,model:modelCalls},callsBeforeReads);
    });
    await t.test('missing model configuration does not block collection, manual statistics or a failed-month retry', async () => {
        const offline = new MarketModuleService({ context: f.context, modelIdentity: () => null });
        failHistory = true; emitEcho=false;
        const start = await offline.startShapes(f.actor, f.scope.researchId, { poolSize: 100, newProductMonths: 6, catalog: { ...request.params.catalog, allowedLabels: [] } }, randomUUID());
        assert.deepEqual(start.run.params.catalog.allowedLabels, [], 'product collection does not require a prewritten shape directory');
        assert.equal(start.run.suggestions.status, 'unavailable');
        assert.equal(start.run.source, null);
        for (let i = 0; i < 12 && await runtime.tick(); i++) { }
        const first = await offline.findShapes(f.actor, start.run.id), failed = first.run.steps.find(s => s.status === 'failed');
        assert.ok(failed);
        assert.equal(first.run.source!.historyAttemptIds.length, 0);
        const command = { referenceAttemptId: first.run.source!.referenceAttemptId, historyAttemptIds: [], expectedParentRevisionId: null, selectedAsins: ['B000000001'], taxonomyVersion: 'test-shapes/v1', labels, assignments: [], bands: [{ id: 'all', minInclusive: 0, maxExclusive: null }] };
        const partial = await offline.saveShapeRevision(f.actor, start.run.id, command, randomUUID());
        assert.equal(partial.revision.labels[0].label,'层架式');
        assert.equal(partial.revision.totalUnits, null);
        assert.equal(partial.revision.coverage, 'none');
        assert.equal(partial.revision.sourcePolicy!.version,'sellersprite-product-source-policy/v1');
        assert.equal(partial.revision.products[0].provenance!.currencyBasis,'provider-contract');
        assert.equal(partial.revision.structure!.ruleVersion, 'market-shape-structure/v2');
        assert.equal(partial.revision.structure!.products[0].listing.ageMonths, 19);
        assert.equal(partial.revision.structure!.segments[0].brands[0].stats.units, null);
        const storedPartial=await new PostgresMarketShapePriceRevisionStore(f.context).find({actor:f.actor,moduleRunId:start.run.id});
        assert.equal(storedPartial!.catalog.version,'market-shape-price-catalog/v3');
        assert.deepEqual(storedPartial!.catalog.structure,partial.revision.structure);
        failHistory = false;
        const before = calls.length;
        await offline.retry(f.actor, start.run.id, { steps: [{ stepId: failed.id, failedAttemptId: failed.latestAttemptId! }] }, randomUUID());
        for (let i = 0; i < 8 && await runtime.tick(); i++) { }
        assert.equal(calls.length, before + 1);
        assert.equal(calls.at(-1), '202607');
        assert.equal(modelCalls, 1);
        const next = await offline.findShapes(f.actor, start.run.id);
        assert.equal(next.run.source!.historyAttemptIds.length, 1);
        assert.equal(next.run.latestRevision!.totalUnits, null);
        const complete = await offline.saveShapeRevision(f.actor, start.run.id, { ...command, expectedParentRevisionId: partial.revision.revisionId, historyAttemptIds: next.run.source!.historyAttemptIds }, randomUUID());
        assert.equal(complete.revision.totalUnits, 20);
        assert.equal(complete.revision.structure!.segments[0].brands[0].stats.units,20);
        const oldStructure=await offline.shapeRevision(f.actor,start.run.id,partial.revision.revisionId);
        assert.equal(oldStructure.revision.structure!.segments[0].brands[0].stats.units,null);
        const reopened=await new PostgresMarketShapePriceRevisionStore(f.context).find({actor:f.actor,moduleRunId:start.run.id});
        assert.deepEqual(reopened!.catalog.structure,complete.revision.structure);
        assert.equal(complete.revision.products[0].observations[0].provenance!.periodBasis,'request-bound');
        const archiveRequest={...request,idempotencyKey:randomUUID(),versions:{...request.versions,rule:'market-shape-price-catalog/v2',model:null,prompt:null,configuration:null}};
        const archive=await f.stores.steps.createModuleRun({...archiveRequest,initialSteps:marketShapeFlowInitialSteps(archiveRequest)});
        for(let i=0;i<8&&await runtime.tick();i++){}
        const archiveView=await offline.findShapes(f.actor,archive.run.id);
        const archiveReport=await offline.saveShapeRevision(f.actor,archive.run.id,{...command,referenceAttemptId:archiveView.run.source!.referenceAttemptId,historyAttemptIds:archiveView.run.source!.historyAttemptIds},randomUUID());
        assert.equal(archiveReport.revision.sourcePolicy,undefined);
        assert.equal(archiveReport.revision.totalUnits,null,'v2 must keep its frozen echo-required admission');
        assert.equal(archiveReport.revision.structure!.ruleVersion,'market-shape-structure/v1');
        const unsupported=await offline.createStudy(f.actor,{marketplace:'US',currency:'USD',nodeIdPath:f.scope.nodeIdPath,fromMonth:'2024-08',toMonth:'2026-08'},randomUUID());
        await assert.rejects(offline.startShapes(f.actor,unsupported.study.id,{poolSize:100,newProductMonths:6,catalog:request.params.catalog},randomUUID()),/24/);
    });
});
