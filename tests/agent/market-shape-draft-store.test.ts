import assert from 'node:assert/strict';
import test from 'node:test';
import {randomUUID} from 'node:crypto';
import {startPostgresTestContainer} from './helpers/postgres-test-container';
import {runPostgresMigrations} from '../../server/db/postgres/migrations';
import {createMarketSemanticFixture} from './helpers/market-semantic-fixture';
import {MarketModuleService} from '../../server/services/market-module-service';
import {PostgresMarketShapeDraftStore} from '../../server/db/postgres/market-shape-draft-store';

test('actor and category drafts survive capacity changes, isolate users and replay lost responses',{timeout:120000},async t=>{
  const pg=await startPostgresTestContainer();t.after(()=>pg.close());await runPostgresMigrations(pg.pool);
  const f=await createMarketSemanticFixture(pg.pool);
  const service=new MarketModuleService({context:f.context,modelIdentity:()=>null});
  const study=await service.createStudy(f.actor,{marketplace:'US',currency:'USD',nodeIdPath:f.scope.nodeIdPath,fromMonth:'2026-07',toMonth:'2026-08'},randomUUID());
  const params=(poolSize:number)=>({poolSize,newProductMonths:6,catalog:{task:'market-product-shape-suggestion',taxonomyVersion:'reference/v1',allowedLabels:[]}});
  const first=await service.startShapes(f.actor,study.study.id,params(1),randomUUID());
  const store=new PostgresMarketShapeDraftStore(f.context);
  assert.equal((await store.find({actor:f.actor,moduleRunId:first.run.id})).draft.version,0);
  const request={expectedVersion:0,items:[{asin:'B000000001',included:false,label:'Floor Lamp'}],catalogLabels:['Floor Lamp']};
  const key=randomUUID();
  const saved=await store.save({actor:f.actor,moduleRunId:first.run.id,request,idempotencyKey:key});
  assert.equal(saved.draft.version,1);
  assert.deepEqual(await store.save({actor:f.actor,moduleRunId:first.run.id,request,idempotencyKey:key}),saved);
  await assert.rejects(store.save({actor:f.actor,moduleRunId:first.run.id,request:{...request,catalogLabels:['Other']},idempotencyKey:key}));
  await assert.rejects(store.save({actor:f.actor,moduleRunId:first.run.id,request:{...request,items:[]},idempotencyKey:randomUUID()}));
  const larger=await service.startShapes(f.actor,study.study.id,params(2),randomUUID());
  assert.deepEqual((await store.find({actor:f.actor,moduleRunId:larger.run.id})).draft,saved.draft);
  assert.deepEqual(await store.save({actor:f.actor,moduleRunId:larger.run.id,request,idempotencyKey:key}),saved,'lost response may replay after capacity changes');
  const concurrentRequest={expectedVersion:1,items:[{asin:'B000000001',included:true,label:'Desk Lamp'}],catalogLabels:['Desk Lamp']};
  const concurrentKey=randomUUID();
  const replies=await Promise.all([store.save({actor:f.actor,moduleRunId:first.run.id,request:concurrentRequest,idempotencyKey:concurrentKey}),store.save({actor:f.actor,moduleRunId:larger.run.id,request:concurrentRequest,idempotencyKey:concurrentKey})]);
  assert.deepEqual(replies[0],replies[1],'overlapping retries of one command return the same receipt');
  assert.equal(replies[0].draft.version,2);
  const otherStudy=await service.createStudy(f.actor,{marketplace:'US',currency:'USD',nodeIdPath:'999:888',fromMonth:'2026-07',toMonth:'2026-08'},randomUUID());
  const otherCategory=await service.startShapes(f.actor,otherStudy.study.id,params(1),randomUUID());
  assert.equal((await store.find({actor:f.actor,moduleRunId:otherCategory.run.id})).draft.version,0);
  const other={organizationId:f.actor.organizationId,userId:randomUUID()};
  await pg.pool.query("INSERT INTO users(id,organization_id,email,display_name,role,status,created_at,updated_at) VALUES($1,$2,$3,'Other','member','active',now(),now())",[other.userId,other.organizationId,`${other.userId}@example.com`]);
  assert.equal((await store.find({actor:other,moduleRunId:first.run.id})).draft.version,0);
});
