import { createRepairSafeRecordMap, isRepairIncomplete, reportIncompleteRepair } from "./lib/sync-cache.mjs";
import fs from "node:fs";
import path from "node:path";
import { generatedAppDataPath } from "./lib/generated-app-data-path.mjs";
import { callSifTool, readSifHeaders } from "./lib/sif-mcp-client.mjs";
import {sourceFetchedDate} from './lib/sorftime-source-policy.mjs';
import {
  isForceRefresh,
  logCacheHit,
  readCachedDataExport,
  shouldUseCachedRecord,
} from "./lib/sync-cache.mjs";

const root = path.resolve(import.meta.dirname, "..");
const catalogPath = generatedAppDataPath(root, "competitor-data.ts");
const listingRawPath = generatedAppDataPath(root, "sif-listing-traffic-raw-data.ts");
const monthlyRawPath = generatedAppDataPath(root, "sif-monthly-traffic-trend-raw-data.ts");

const TRAFFIC_QUERY = {
  timePieceType: "latelyDay",
  timePieceValue: "30",
  isListingSearch: true,
};

function readCatalogAsins() {
  const source = fs.readFileSync(catalogPath, "utf8");
  return [...source.matchAll(/"asin":\s*"([A-Z0-9]{10})"/g)].map(match => match[1]);
}

function extractAsin(value) {
  const match = String(value).match(/B0[A-Z0-9]{8}/i);
  return match ? match[0].toUpperCase() : String(value).trim().toUpperCase();
}

function parseUpdatedThrough(notice) {
  const match = String(notice ?? "").match(/(\d{4}-\d{2}-\d{2})/);
  return match?.[1] ?? null;
}

function normalizeOverview(payload) {
  return {
    overview: {
      nf: { score: payload.overview?.nf?.score ?? 0, ratio: payload.overview?.nf?.ratio ?? 0 },
      ad: { score: payload.overview?.ad?.score ?? 0, ratio: payload.overview?.ad?.ratio ?? 0 },
    },
    ad: payload.ad ?? {},
    recommend: payload.recommend ?? {},
    total: payload.total ?? 0,
    data_notice: payload.data_notice ?? "",
  };
}

function normalizeStructure(payload) {
  const chars = payload.chars ?? {};
  const dims = (chars.dims ?? []).map(dim => ({
    img: dim.img ?? "",
    features: dim.features ?? [],
    sumScore: dim.sumScore ?? 0,
    ratio: dim.ratio ?? 0,
    val: extractAsin(dim.val),
  }));
  const pickScores = key =>
    (chars[key] ?? []).map(item => ({ score: item?.score ?? 0 }));

  return {
    chars: {
      dims,
      nfs: pickScores("nfs"),
      sps: pickScores("sps"),
      recs: pickScores("recs"),
      sbs: pickScores("sbs"),
      sbvs: pickScores("sbvs"),
    },
    data_notice: payload.data_notice ?? "",
  };
}

function normalizeMonthlyTrend(payload) {
  const dates = payload.dates ?? [];
  const nf = (payload.nfScore ?? []).map(item => ({ score: item?.score ?? 0 }));
  const ad = (payload.adScore ?? []).map(item => ({ score: item?.score ?? 0 }));
  return { dates, nf, ad, data_notice: payload.data_notice ?? "" };
}

function writeListingRawFile(records, meta) {
  const body = `// Generated by scripts/build-sif-listing-traffic.mjs — do not edit manually
export const sifListingTrafficRawMeta = ${JSON.stringify(meta, null, 2)} as const;

export const sifListingTrafficRawByAsin = ${JSON.stringify(records, null, 2)};
`;
  fs.writeFileSync(listingRawPath, body, "utf8");
}

function writeMonthlyRawFile(records, meta) {
  const body = `// Generated by scripts/build-sif-listing-traffic.mjs — do not edit manually
export const sifMonthlyTrafficRawMeta = ${JSON.stringify(meta, null, 2)} as const;

export const sifMonthlyTrafficRawByAsin = ${JSON.stringify(records, null, 2)};
`;
  fs.writeFileSync(monthlyRawPath, body, "utf8");
}

async function main() {
  const headers = readSifHeaders();
  const marketplace = process.env.SIF_MARKETPLACE ?? "US";
  const asins =
    process.env.SIF_ASINS?.split(",")
      .map(item => item.trim())
      .filter(Boolean) ?? readCatalogAsins();
  if (process.env.SIF_ASINS?.trim()) {
    console.log(`[sync] SIF_ASINS=${process.env.SIF_ASINS.trim()} · 仅同步指定 ASIN（其余缓存保留）`);
  }
  const fetchedAt = new Date().toISOString().slice(0, 10);

  const existingListing = readCachedDataExport(listingRawPath, "sifListingTrafficRawByAsin");
  const existingMonthly = readCachedDataExport(monthlyRawPath, "sifMonthlyTrafficRawByAsin");
  const listingRecords = createRepairSafeRecordMap(existingListing);
  const monthlyRecords = createRepairSafeRecordMap(existingMonthly);

  if (!headers && !Object.keys(existingListing).length) {
    console.error("[error] 未找到 SIF MCP 密钥，且无可用流量缓存");
    process.exitCode = 1;
    return;
  }

  if (isForceRefresh()) console.log("[sync] FORCE_REFRESH=1 · 忽略缓存，重新调用 MCP");

  let latestNotice = null;

  for (const asin of asins) {
    const cachedListing = existingListing[asin];
    const cachedMonthly = existingMonthly[asin];
    const listingReady = cachedListing?.overview?.total > 0 && cachedListing?.structure?.chars?.dims?.length;
    const monthlyReady = cachedMonthly?.dates?.length && cachedMonthly?.nf?.length;

    if (
      !isForceRefresh() &&
      shouldUseCachedRecord({ status: listingReady && monthlyReady ? "ready" : "missing", fetchedAt: cachedListing?.fetchedAt }) &&
      listingReady &&
      monthlyReady
    ) {
      logCacheHit(asin, { fetchedAt: cachedListing?.fetchedAt ?? cachedMonthly?.fetchedAt });
      latestNotice = cachedListing?.overview?.data_notice ?? cachedMonthly?.data_notice ?? latestNotice;
      continue;
    }

    if (!headers) {
      console.log(`[skip] ${asin} · 无 MCP key，保留已有缓存或跳过`);
      continue;
    }

    if (isRepairIncomplete()) {
      // Commit each missing part separately: a failed sibling must not lose a successful response.
      for (const part of ["overview", "structure", "monthly"]) {
        const complete = part === "overview" ? cachedListing?.overview?.total > 0
          : part === "structure" ? cachedListing?.structure?.chars?.dims?.length > 0 : monthlyReady;
        if (complete) continue;
        try {
          const payload = await callSifTool(part === "overview" ? "ops_get_listing_traffic_overview"
            : part === "structure" ? "ops_get_listing_traffic_structure" : "ops_get_asin_traffic_trend", {
            asin, country: marketplace,
            ...(part === "monthly" ? {granularity: "month", lastMonths: 6, listingSearch: true}
              : {...TRAFFIC_QUERY, ...(part === "structure" ? {pageSize: 20} : {})}),
          });
          const value = part === "overview" ? normalizeOverview(payload) : part === "structure" ? normalizeStructure(payload) : normalizeMonthlyTrend(payload);
          const valid = part === "overview" ? value.total > 0 : part === "structure" ? value.chars.dims.length > 0 : value.dates.length && value.nf.length;
          if (!valid) throw new Error(`${part}: empty provider response`);
          const sourceDate=sourceFetchedDate([payload],fetchedAt);
          if (part === "monthly") monthlyRecords[asin] = {fetchedAt:sourceDate, ...value};
          else listingRecords[asin] = {...listingRecords[asin], fetchedAt: [listingRecords[asin]?.fetchedAt,sourceDate].filter(Boolean).sort()[0], [part]: value};
          latestNotice = payload.data_notice ?? latestNotice;
        } catch (error) {
          console.error(`[repair-incomplete] ${asin} ${part}: ${error instanceof Error ? error.message : String(error)}`);
          reportIncompleteRepair(asin);
        }
      }
      continue;
    }

    process.stdout.write(`[traffic] ${asin} listing overview ... `);
    try {
      const overviewPayload = await callSifTool("ops_get_listing_traffic_overview", {
        asin,
        country: marketplace,
        ...TRAFFIC_QUERY,
      });
      const structurePayload = await callSifTool("ops_get_listing_traffic_structure", {
        asin,
        country: marketplace,
        timePieceType: TRAFFIC_QUERY.timePieceType,
        timePieceValue: TRAFFIC_QUERY.timePieceValue,
        pageSize: 20,
      });
      const trendPayload = await callSifTool("ops_get_asin_traffic_trend", {
        asin,
        country: marketplace,
        granularity: "month",
        lastMonths: 6,
        listingSearch: true,
      });

      listingRecords[asin] = {
        fetchedAt:sourceFetchedDate([overviewPayload,structurePayload],fetchedAt),
        overview: normalizeOverview(overviewPayload),
        structure: normalizeStructure(structurePayload),
      };
      monthlyRecords[asin] = {
        fetchedAt:sourceFetchedDate([trendPayload],fetchedAt),
        ...normalizeMonthlyTrend(trendPayload),
      };
      latestNotice =
        overviewPayload.data_notice ?? trendPayload.data_notice ?? latestNotice;
      console.log("ok");
    } catch (error) {
      if (listingReady || monthlyReady) {
        console.log(`error · keep cache (${error instanceof Error ? error.message : String(error)})`);
        continue;
      }
      console.log(`error: ${error instanceof Error ? error.message : String(error)}`);
    }

    await new Promise(resolve => setTimeout(resolve, 400));
  }

  const updatedThrough = parseUpdatedThrough(latestNotice) ?? fetchedAt;
  const meta = {
    source: "SIF MCP · ops_get_listing_traffic_overview + ops_get_listing_traffic_structure + ops_get_asin_traffic_trend",
    period: "近30天 Listing 结构 · 近6个月月趋势",
    country: marketplace,
    updatedAt: fetchedAt,
    updatedThrough,
    syncCommand: "npm run traffic:sync",
    cachePolicy: "默认使用本地缓存；FORCE_REFRESH=1 或 --force 强制刷新",
  };

  writeListingRawFile(listingRecords, meta);
  writeMonthlyRawFile(monthlyRecords, meta);

  const ready = asins.filter(asin => listingRecords[asin]?.overview?.total > 0).length;
  console.log(`[done] ${ready}/${asins.length} ASIN → listing + monthly traffic raw data`);
}

main();
