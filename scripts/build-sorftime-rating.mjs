import fs from "node:fs";
import path from "node:path";
import { callSorftimeTool, readSorftimeKey } from "./lib/sorftime-mcp-client.mjs";
import {
  isForceRefresh,
  logCacheHit,
  readCachedDataExport,
  shouldUseCachedRecord,
} from "./lib/sync-cache.mjs";

const root = path.resolve(import.meta.dirname, "..");
const catalogPath = path.join(root, "app", "competitor-data.ts");
const outPath = path.join(root, "app", "sorftime-rating-data.ts");

function readCatalogAsins() {
  const source = fs.readFileSync(catalogPath, "utf8");
  return [...source.matchAll(/"asin":\s*"([A-Z0-9]{10})"/g)].map(match => match[1]);
}

function toNumber(value) {
  const num = Number(value);
  return Number.isFinite(num) ? num : null;
}

async function main() {
  const key = readSorftimeKey();
  const marketplace = process.env.SORFTIME_MARKETPLACE ?? "US";
  const asins = process.env.SORFTIME_ASINS?.split(",").map(item => item.trim()).filter(Boolean) ?? readCatalogAsins();
  const fetchedAt = new Date().toISOString().slice(0, 10);
  const existing = readCachedDataExport(outPath, "sorftimeRatingData");
  const records = { ...existing };

  if (!key && !Object.values(existing).some(record => record?.status === "ready")) {
    console.error("[error] 未找到 Sorftime MCP key，且无可用缓存");
    process.exitCode = 1;
    return;
  }

  if (isForceRefresh()) console.log("[sync] FORCE_REFRESH=1 · 忽略缓存，重新调用 MCP");

  for (const asin of asins) {
    if (shouldUseCachedRecord(existing[asin]) && existing[asin]?.status === "ready") {
      logCacheHit(asin, existing[asin]);
      continue;
    }

    if (!key) {
      console.log(`[skip] ${asin} · 无 MCP key，保留已有缓存或跳过`);
      continue;
    }

    process.stdout.write(`[rating] ${asin} ... `);
    try {
      const detailRaw = await callSorftimeTool(key, "product_detail", { asin, amz_site: marketplace });
      const detail = detailRaw?.data ?? detailRaw;
      const rating = toNumber(detail?.star_rating);
      const reviewCount = toNumber(detail?.review_count);

      if (rating == null && reviewCount == null) {
        records[asin] = {
          asin,
          marketplace,
          fetchedAt,
          status: "empty",
          rating: null,
          reviewCount: null,
        };
        console.log("empty");
      } else {
        records[asin] = {
          asin,
          marketplace,
          fetchedAt,
          status: "ready",
          rating,
          reviewCount,
        };
        console.log(`${rating ?? "—"} · ${reviewCount?.toLocaleString() ?? "—"} reviews`);
      }
    } catch (error) {
      if (existing[asin]?.status === "ready") {
        console.log(`failed · keep cache (${error instanceof Error ? error.message : String(error)})`);
        continue;
      }
      records[asin] = {
        asin,
        marketplace,
        fetchedAt,
        status: "error",
        statusMessage: error instanceof Error ? error.message : String(error),
        rating: null,
        reviewCount: null,
      };
      console.log(`failed (${records[asin].statusMessage})`);
    }
    await new Promise(resolve => setTimeout(resolve, 300));
  }

  const body = `// Generated by scripts/build-sorftime-rating.mjs — do not edit manually
export type SorftimeRatingRecord = {
  asin: string;
  marketplace: string;
  fetchedAt: string;
  status: "ready" | "empty" | "error";
  statusMessage?: string;
  rating: number | null;
  reviewCount: number | null;
};

export const sorftimeRatingMeta = ${JSON.stringify(
    {
      source: "Sorftime MCP · product_detail（star_rating / review_count）",
      updatedAt: fetchedAt,
      marketplace,
      syncCommand: "npm run rating:sync",
      cachePolicy: "默认使用本地缓存；FORCE_REFRESH=1 或 --force 强制刷新",
    },
    null,
    2
  )} as const;

export const sorftimeRatingData: Record<string, SorftimeRatingRecord> = ${JSON.stringify(records, null, 2)};
`;

  fs.writeFileSync(outPath, body, "utf8");
  console.log(`[done] wrote ${outPath}`);
}

main().catch(error => {
  console.error(`[error] ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
});
