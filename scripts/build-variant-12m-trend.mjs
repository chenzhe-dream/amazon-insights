import fs from "node:fs";
import path from "node:path";
import { callSellerSpriteMcpTool, readSellerSpriteSecretKey } from "./lib/sellersprite-mcp-client.mjs";
import {
  isForceRefresh,
  logCacheHit,
  readCachedDataExport,
  shouldUseCachedRecord,
} from "./lib/sync-cache.mjs";

const root = path.resolve(import.meta.dirname, "..");
const variantPath = path.join(root, "app", "variant-data.ts");
const outPath = path.join(root, "app", "variant-12m-trend-data.ts");

function readVariantChildAsins() {
  const source = fs.readFileSync(variantPath, "utf8");
  const asins = [...source.matchAll(/"asin":\s*"([A-Z0-9]{10})"/g)].map(m => m[1]);
  const sales = [...source.matchAll(/"childSales":\s*(null|\d+)/g)].map(m => (m[1] === "null" ? null : Number(m[1])));
  const reviews = [...source.matchAll(/"reviews":\s*(null|\d+)/g)].map(m => (m[1] === "null" ? null : Number(m[1])));
  const rows = asins.map((asin, index) => ({
    asin,
    childSales: sales[index] ?? null,
    reviews: reviews[index] ?? null,
  }));

  const bySales = [...rows]
    .filter(row => row.childSales != null)
    .sort((a, b) => (b.childSales ?? 0) - (a.childSales ?? 0));
  const byReviews = [...rows]
    .filter(row => row.reviews != null)
    .sort((a, b) => (b.reviews ?? 0) - (a.reviews ?? 0));

  const picked = new Set();
  for (const row of [...bySales.slice(0, 10), ...byReviews.slice(0, 10)]) picked.add(row.asin);
  return [...picked];
}

function sleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

function last12CompleteMonths(points) {
  const sorted = [...points]
    .filter(point => point.month && Number.isFinite(point.childUnitSales))
    .sort((a, b) => a.month.localeCompare(b.month));
  // Drop incomplete trailing month if null already filtered; keep last 12
  return sorted.slice(-12);
}

async function main() {
  const key = readSellerSpriteSecretKey();
  const marketplace = process.env.SELLERSPRITE_MARKETPLACE ?? "US";
  const asins = process.env.VARIANT_TREND_ASINS?.split(",").map(item => item.trim()).filter(Boolean) ?? readVariantChildAsins();
  const fetchedAt = new Date().toISOString().slice(0, 10);
  const existing = readCachedDataExport(outPath, "variant12mTrendData");
  const records = { ...existing };

  if (!key && !Object.values(existing).some(record => record.status === "ready")) {
    console.error("[error] 未找到卖家精灵 MCP secret-key，且无可用缓存");
    process.exitCode = 1;
    return;
  }

  if (isForceRefresh()) console.log("[sync] FORCE_REFRESH=1 · 忽略缓存，重新调用 MCP");
  console.log(`[plan] sync ${asins.length} child ASINs for 12m trend`);

  for (const asin of asins) {
    if (shouldUseCachedRecord(existing[asin])) {
      logCacheHit(asin, existing[asin]);
      continue;
    }
    if (!key) {
      console.log(`[skip] ${asin} · 无 MCP key`);
      continue;
    }

    process.stdout.write(`[12m] ${asin} ... `);
    try {
      const raw = await callSellerSpriteMcpTool(key, "asin_sales_trend", { marketplace, asin });
      if (raw?.code && raw.code !== "OK") throw new Error(`${raw.code}: ${raw.message ?? "asin_sales_trend failed"}`);
      const points = last12CompleteMonths(raw?.data?.salesTrendPoints ?? []);
      const total12m = points.reduce((sum, point) => sum + (point.childUnitSales ?? 0), 0);
      const avg12m = points.length ? Math.round(total12m / points.length) : 0;
      records[asin] = {
        asin,
        marketplace,
        fetchedAt,
        status: points.length ? "ready" : "empty",
        total12m,
        avg12m,
        months: points.map(point => ({
          month: point.month,
          childSales: point.childUnitSales ?? 0,
          parentSales: point.parentUnitSales ?? null,
          price: point.averagePrice ?? point.price ?? null,
        })),
      };
      console.log(`${points.length} months · avg ${avg12m}`);
    } catch (error) {
      if (existing[asin]?.status === "ready") {
        console.log(`error · keep cache (${error instanceof Error ? error.message : String(error)})`);
        continue;
      }
      records[asin] = {
        asin,
        marketplace,
        fetchedAt,
        status: "error",
        statusMessage: error instanceof Error ? error.message : String(error),
        total12m: 0,
        avg12m: 0,
        months: [],
      };
      console.log(`error: ${records[asin].statusMessage}`);
    }
    await sleep(350);
  }

  const body = `// Generated by scripts/build-variant-12m-trend.mjs — do not edit manually
export type Variant12mMonthPoint = {
  month: string;
  childSales: number;
  parentSales: number | null;
  price: number | null;
};

export type Variant12mTrendRecord = {
  asin: string;
  marketplace: string;
  fetchedAt: string;
  status: "ready" | "empty" | "error";
  statusMessage?: string;
  total12m: number;
  avg12m: number;
  months: Variant12mMonthPoint[];
};

export const variant12mTrendMeta = ${JSON.stringify(
    {
      source: "卖家精灵 MCP · asin_sales_trend · childUnitSales",
      updatedAt: fetchedAt,
      marketplace,
      syncCommand: "npm run variant12m:sync",
      note: "上架时间跨度过大时，用近12个月子体销量校准表现",
    },
    null,
    2,
  )} as const;

export const variant12mTrendData: Record<string, Variant12mTrendRecord> = ${JSON.stringify(records, null, 2)};
`;
  fs.writeFileSync(outPath, body, "utf8");
  const ready = Object.values(records).filter(record => record.status === "ready").length;
  console.log(`[done] ${ready}/${asins.length} ASINs → app/variant-12m-trend-data.ts`);
}

main();
