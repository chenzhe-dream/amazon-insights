async function main() {
  const headers = readSifHeaders();
  const marketplace = process.env.SIF_MARKETPLACE ?? "US";
  const topN = Number.parseInt(process.env.SIF_KEYWORD_TOPN ?? "50", 10);
  const asins =
    process.env.SIF_ASINS?.split(",")
      .map(item => item.trim())
      .filter(Boolean) ?? readCatalogAsins();
  const fetchedAt = new Date().toISOString().slice(0, 10);
  const existing = readCachedDataExport(outPath, "sifKeywordAnalysisData");
  const existingEnrichment = readCachedDataExport(enrichPath, "sifKeywordEnrichmentData");
  const records = createRepairSafeRecordMap(existing);
  const historicalFallback = process.env.AGENT_SIF_EMPTY_PREVIOUS_MONTH_FALLBACK === "1";
  const collectionNow = new Date();

  if (!headers && !Object.values(existing).some(record => record.status === "ready")) {
    console.error("[error] 未找到 SIF MCP 密钥，且无可用缓存");
    process.exitCode = 1;
    return;
  }

  if (isForceRefresh()) console.log("[sync] FORCE_REFRESH=1 · 忽略缓存，重新调用 MCP");

  for (const asin of asins) {
    if (hasCompleteKeywordRecord(existing[asin]) && matchesKeywordQueryWindow(existing[asin], { enabled: historicalFallback, now: collectionNow, marketplace }) && (isRepairIncomplete() || shouldUseCachedRecord(existing[asin]))) {
      logCacheHit(asin, existing[asin]);
      continue;
    }
    if (shouldUseCachedRecord(existing[asin]) && !matchesKeywordQueryWindow(existing[asin], { enabled: historicalFallback, now: collectionNow, marketplace })) {
      console.log(`[refresh] ${asin} · 缓存为旧口径（非近30天 listingSearch），重新拉取`);
    }

    if (!headers) {
      console.log(`[skip] ${asin} · 无 MCP key，保留已有缓存或跳过`);
      continue;
    }

    process.stdout.write(`[sif] ${asin} keyword signals ... `);
    try {
      records[asin] = await collectSifKeywordWithPreviousMonth({
        asin, marketplace, fetchedAt, topN, enabled: historicalFallback, now: collectionNow,
        call: callSifTool,
      });
      console.log(`${records[asin].keywords.length} keywords`);
    } catch (error) {
      if (existing[asin]?.status === "ready") {
        console.log(`error · keep cache (${error instanceof Error ? error.message : String(error)})`);
        continue;
      }
      records[asin] = {
        asin,
        marketplace,
        fetchedAt,
        status: "error",
        statusMessage: error instanceof Error ? error.message : String(error),
        totalKeywordsInPeriod: null,
        topKeywordsAnalyzed: 0,
        keywords: [],
      };
      console.log(`error: ${records[asin].statusMessage}`);
    }
    await new Promise(resolve => setTimeout(resolve, 400));
  }

  writeKeywordAnalysisFile(records, fetchedAt, marketplace);
  const ready = Object.values(records).filter(record => record.status === "ready").length;
  console.log(`[done] ${ready}/${asins.length} ASIN → app/sif-keyword-analysis-data.ts`);

  const uniqueKeywords = collectUniqueKeywords(isRepairIncomplete() ? Object.fromEntries(asins.map(asin => [asin, records[asin]])) : records);
  if (!uniqueKeywords.length) {
    writeKeywordEnrichmentFile(existingEnrichment, fetchedAt, marketplace);
    return;
  }

  if (!headers) {
    console.log("[skip] keyword enrichment · 无 MCP key");
    writeKeywordEnrichmentFile(existingEnrichment, fetchedAt, marketplace);
    return;
  }

  const enrichment = isForceRefresh()
    ? await enrichKeywords(uniqueKeywords, marketplace, fetchedAt, {})
    : await enrichKeywords(uniqueKeywords, marketplace, fetchedAt, existingEnrichment);

  writeKeywordEnrichmentFile(enrichment, fetchedAt, marketplace);
  const enrichedReady = Object.values(enrichment).filter(record => record.status === "ready").length;
  console.log(`[done] ${enrichedReady}/${uniqueKeywords.length} keywords enriched → app/sif-keyword-enrichment-data.ts`);
}

main();
