import fs from "node:fs";
import path from "node:path";
import { buildReviewAnalysisFromRecords } from "./lib/review-analysis-aggregate.mjs";

const root = path.resolve(import.meta.dirname, "..");
const defaultAsins = [
  "B07VY9Q95Q",
  "B0BPXRVWYK",
  "B07DYG1C9B",
  "B07S64PYMM",
  "B08HJ96QJ9",
  "B08T8RY9VK",
];

function readSecretKey() {
  if (process.env.SELLERSPRITE_SECRET_KEY) return process.env.SELLERSPRITE_SECRET_KEY;
  const mcpPath = path.join(process.env.USERPROFILE ?? process.env.HOME ?? "", ".cursor", "mcp.json");
  if (!fs.existsSync(mcpPath)) return null;
  const config = JSON.parse(fs.readFileSync(mcpPath, "utf8"));
  return config?.mcpServers?.["sellersprite-mcp"]?.headers?.["secret-key"] ?? null;
}

async function fetchReviewPage(secretKey, marketplace, asin, page, size = 10) {
  const response = await fetch("https://api.sellersprite.com/v1/review", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "secret-key": secretKey,
    },
    body: JSON.stringify({ marketplace, asin, page, size }),
  });

  const payload = await response.json();
  if (payload.code !== "OK") {
    throw new Error(`${payload.code ?? response.status}: ${payload.message ?? "review 请求失败"}`);
  }

  return payload.data?.items ?? payload.data?.list ?? payload.data ?? [];
}

async function fetchReviewsForAsin(secretKey, marketplace, asin, maxPages = 8) {
  const reviews = [];
  const seen = new Set();

  for (let page = 1; page <= maxPages; page += 1) {
    const items = await fetchReviewPage(secretKey, marketplace, asin, page);
    if (!Array.isArray(items) || !items.length) break;

    items.forEach(item => {
      const key = `${item.author ?? ""}|${item.date ?? ""}|${(item.content ?? "").slice(0, 40)}`;
      if (seen.has(key)) return;
      seen.add(key);
      reviews.push(item);
    });

    if (items.length < 10) break;
    await new Promise(resolve => setTimeout(resolve, 250));
  }

  return reviews;
}

function writeDataFile(records, meta) {
  const target = path.join(root, "app", "seller-sprite-review-analysis-data.ts");
  const body = `// Generated by scripts/fetch-sellersprite-review-analysis.mjs — do not edit manually
import type { SellerSpriteReviewAnalysisRecord } from "./seller-sprite-review-analysis";

export const sellerSpriteReviewAnalysisMeta = ${JSON.stringify(meta, null, 2)} as const;

export const sellerSpriteReviewAnalysisData: Record<string, SellerSpriteReviewAnalysisRecord> = ${JSON.stringify(records, null, 2)};
`;
  fs.writeFileSync(target, body, "utf8");
}

async function main() {
  const secretKey = readSecretKey();
  const marketplace = process.env.SELLERSPRITE_MARKETPLACE ?? "US";
  const asins = (process.env.SELLERSPRITE_ASINS ?? defaultAsins.join(",")).split(",").map(v => v.trim()).filter(Boolean);
  const fetchedAt = new Date().toISOString().slice(0, 10);
  const records = {};

  if (!secretKey) {
    console.error("[error] 未找到 SELLERSPRITE_SECRET_KEY 或 ~/.cursor/mcp.json 中的 sellersprite-mcp secret-key");
    process.exitCode = 1;
    asins.forEach(asin => {
      records[asin] = {
        asin,
        marketplace,
        sampledReviews: 0,
        fetchedAt,
        status: "error",
        statusMessage: "缺少卖家精灵 secret-key",
        blocks: [],
      };
    });
    writeDataFile(records, {
      source: "卖家精灵 MCP · review",
      updatedAt: fetchedAt,
      syncStatus: "missing-key",
    });
    return;
  }

  for (const asin of asins) {
    process.stdout.write(`[fetch] ${asin} ... `);
    try {
      const reviews = await fetchReviewsForAsin(secretKey, marketplace, asin);
      records[asin] = buildReviewAnalysisFromRecords(asin, marketplace, reviews, fetchedAt);
      console.log(`${reviews.length} reviews`);
    } catch (error) {
      records[asin] = {
        asin,
        marketplace,
        sampledReviews: 0,
        fetchedAt,
        status: "error",
        statusMessage: error instanceof Error ? error.message : String(error),
        blocks: [],
      };
      console.log(`failed (${records[asin].statusMessage})`);
    }
  }

  writeDataFile(records, {
    source: "卖家精灵 MCP · review",
    updatedAt: fetchedAt,
    marketplace,
    syncStatus: Object.values(records).some(record => record.status === "ready") ? "partial-or-ok" : "failed",
  });

  const ready = Object.values(records).filter(record => record.status === "ready").length;
  console.log(`[done] ${ready}/${asins.length} ASIN 已生成简化评论分析 → app/seller-sprite-review-analysis-data.ts`);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
