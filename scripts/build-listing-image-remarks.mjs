const root = path.resolve(import.meta.dirname, "..");
const catalogPath = generatedAppDataPath(root, "competitor-data.ts");
const listingPath = generatedAppDataPath(root, "sorftime-listing-content-data.ts");
const outPath = generatedAppDataPath(root, "listing-image-remarks.ts");

const SKILL_PROMPT = `你是电商 Listing 主辅图视觉分析助手。分析这张商品图片，只依据画面中可见内容，返回 JSON：
{
  "image_types": ["1-3个中文类型"],
  "remark": "20-80字中文，展示方式+核心卖点",
  "confidence": "high|medium|low"
}
类型从以下选择：产品展示、核心卖点、功能展示、产品细节、结构展示、尺寸参数、使用场景、使用效果、人群展示、使用方法、折叠/收纳、灯光/视觉效果、多颜色/多款式、品牌形象、其他。
除非图片中的可见文字明确写明，否则不得声称防漏、无滴漏、耐用、安全等功能属性，也不得推断使用场景或使用时机；未有文字依据时只描述可见结构、设计与呈现。
禁止编造图片中没有的信息。`;

function readCatalogAsins() {
  const source = fs.readFileSync(catalogPath, "utf8");
  return [...source.matchAll(/"asin":\s*"([A-Z0-9]{10})"/g)].map(match => match[1]);
}

function isVideoThumb(url) {
  return /play-button|PKplay-button/i.test(url);
}

function remarksComplete(asin, record, remarks, imageUrlsByAsin = {}) {
  return hasCompleteImageRemarks(record, remarks[asin], imageUrlsByAsin[asin]);
}

async function analyzeWithOpenAI(imageUrl, slotIndex, asin, signal) {
  const apiKey = process.env.OPENAI_API_KEY?.trim();
  if (!apiKey) return null;

  return requestImageRemark({
    endpoint: imageRemarkEndpoint(),
    apiKey,
    signal,
    model: imageRemarkModel(),
    prompt: `${SKILL_PROMPT}\nASIN: ${asin} · 图片${slotIndex + 1}`,
    imageUrl,
  });
}

function renderRemarksFile(remarks, fetchedAt, extraMeta = {}) {
  const body = `// Generated by scripts/build-listing-image-remarks.mjs — do not edit manually
export type ListingImageRemark = {
  remark: string;
  imageUrl?: string;
  image_types: string[];
  confidence: "high" | "medium" | "low";
};

export const listingImageRemarksMeta = ${JSON.stringify(
    {
      source: "ecommerce-product-image-analysis",
      updatedAt: fetchedAt,
      syncCommand: "npm run image-remarks:sync",
      requiresOpenAI: "OPENAI_API_KEY",
      ...extraMeta,
    },
    null,
    2,
  )} as const;

/** 按 ASIN 索引，数组下标 0 = 图片1（主图），1 = 图片2（辅图）… */
export const listingImageRemarks: Record<string, Array<ListingImageRemark | null>> = ${JSON.stringify(remarks, null, 2)};

export function getListingImageRemark(asin: string, slotIndex: number): ListingImageRemark | null {
  return listingImageRemarks[asin]?.[slotIndex] ?? null;
}
`;
  return body;
}

function isExplicitImageAction() {
  return ["refresh", "analyze"].includes(process.env.AGENT_SYNC_IMAGE_ACTION);
}

async function writeRemarksFile({
  ownedAsins,
  remarkUpdates,
  fetchedAt,
  extraMeta = {},
  listingByAsin = {},
}) {
  const release = await acquireInterprocessLock(`${outPath}.lock`);
  const temporary = path.join(
    path.dirname(outPath),
    `.${path.basename(outPath)}.tmp-${process.pid}-${randomUUID()}`,
  );
  try {
    const latestRemarks = readCachedDataExport(outPath, "listingImageRemarks");
    const latestMeta = readCachedDataExport(outPath, "listingImageRemarksMeta");
    const imageUrlsByAsin = { ...(latestMeta.imageUrlsByAsin ?? {}) };
    const imageOutcomesByAsin = { ...(latestMeta.imageOutcomesByAsin ?? {}) };
    for (const asin of ownedAsins) {
      const gallery = listingByAsin[asin]?.galleryImages;
      if (listingByAsin[asin]?.status !== "ready" || !Array.isArray(gallery)) continue;
      const previous = imageUrlsByAsin[asin] ?? latestRemarks[asin]?.map(remark => remark?.imageUrl);
      latestRemarks[asin] = reconcileListingImageRemarks(previous, gallery, latestRemarks[asin])
        .map((remark, slotIndex) => remark ? { ...remark, imageUrl: gallery[slotIndex] } : null);
      imageOutcomesByAsin[asin] = reconcileListingImageRemarks(
        previous, gallery, imageOutcomesByAsin[asin],
      );
      imageUrlsByAsin[asin] = [...gallery];
    }
    for (const { asin, slotIndex, remark } of remarkUpdates) {
      const slots = Array.isArray(latestRemarks[asin]) ? [...latestRemarks[asin]] : [];
      const imageUrl = listingByAsin[asin]?.galleryImages?.[slotIndex];
      if (remark && (!imageUrl || (remark.imageUrl && remark.imageUrl !== imageUrl))) {
        throw new Error(`Image remark URL does not match the persisted listing for ${asin}:${slotIndex}`);
      }
      slots[slotIndex] = remark ? { ...remark, imageUrl } : null;
      latestRemarks[asin] = slots;
    }

    const owned = new Set(ownedAsins);
    const pendingAsins = new Set(
      (Array.isArray(latestMeta.pendingAsins) ? latestMeta.pendingAsins : [])
        .filter(asin => !owned.has(asin)),
    );
    for (const asin of extraMeta.pendingAsins ?? []) pendingAsins.add(asin);
    for (const [asin, incoming] of Object.entries(extraMeta.imageOutcomesByAsin ?? {})) {
      const slots = Array.isArray(imageOutcomesByAsin[asin])
        ? [...imageOutcomesByAsin[asin]]
        : [];
      for (let slotIndex = 0; slotIndex < incoming.length; slotIndex += 1) {
        if (incoming[slotIndex] === undefined) continue;
        slots[slotIndex] = incoming[slotIndex] === null
          ? null
          : imageRemarkOutcome(incoming[slotIndex]?.status, {
            attemptJobId: incoming[slotIndex]?.attemptJobId,
            diagnostic: incoming[slotIndex]?.diagnostic,
          });
      }
      imageOutcomesByAsin[asin] = slots;
    }
    const imageStatusByAsin = {
      ...(latestMeta.imageStatusByAsin ?? {}),
      ...(extraMeta.imageStatusByAsin ?? {}),
    };
    const affectedAsins = new Set([
      ...ownedAsins,
      ...remarkUpdates.map(update => update.asin),
      ...Object.keys(extraMeta.imageOutcomesByAsin ?? {}),
    ]);
    for (const asin of affectedAsins) {
      const record = listingByAsin[asin];
      if (record?.status !== "ready" || !Array.isArray(record.galleryImages)) continue;
      const slots = Array.isArray(imageOutcomesByAsin[asin])
        ? [...imageOutcomesByAsin[asin]]
        : [];
      const staticResults = [];
      for (let slotIndex = 0; slotIndex < record.galleryImages.length; slotIndex += 1) {
        if (isVideoThumb(record.galleryImages[slotIndex])) {
          slots[slotIndex] = null;
          continue;
        }
        if (latestRemarks[asin]?.[slotIndex]?.remark?.trim() &&
          latestRemarks[asin]?.[slotIndex]?.imageUrl === record.galleryImages[slotIndex] &&
          (!isExplicitImageAction() || !slots[slotIndex] || slots[slotIndex].status === "ready")) {
          slots[slotIndex] = imageRemarkOutcome("ready");
        } else if (slots[slotIndex]) {
          slots[slotIndex] = imageRemarkOutcome(slots[slotIndex].status, {
            attemptJobId: slots[slotIndex].attemptJobId,
            diagnostic: slots[slotIndex].diagnostic,
          });
        }
        staticResults.push(slots[slotIndex] ?? imageRemarkOutcome("upstream-empty"));
      }
      imageOutcomesByAsin[asin] = slots;
      const persistedComplete = remarksComplete(asin, record, latestRemarks, imageUrlsByAsin) &&
        (!isExplicitImageAction() || staticResults.every(outcome => outcome.status === "ready"));
      imageStatusByAsin[asin] = aggregateImageRemarkResults(staticResults, {
        completeWithoutWork: persistedComplete,
        persistedComplete,
      });
      if (persistedComplete) pendingAsins.delete(asin);
      else pendingAsins.add(asin);
    }
    const mergedMeta = {
      ...latestMeta,
      ...extraMeta,
      imageUrlsByAsin,
      pendingAsins: [...pendingAsins].sort(),
      pendingReason: pendingAsins.size
        ? (extraMeta.pendingReason ?? latestMeta.pendingReason ?? "analysis_incomplete")
        : null,
      imageStatusByAsin,
      imageOutcomesByAsin,
    };
    fs.writeFileSync(
      temporary,
      renderRemarksFile(latestRemarks, fetchedAt, mergedMeta),
      { encoding: "utf8", flag: "wx", mode: 0o600 },
    );
    fs.renameSync(temporary, outPath);
  } catch (error) {
    try {
      fs.rmSync(temporary, { force: true });
    } catch {}
    throw error;
  } finally {
    await release();
  }
}

async function main() {
  const analysisAsins =
    process.env.REMARK_ASINS?.split(",")
      .map(item => item.trim())
      .filter(Boolean) ?? readCatalogAsins();
  const fetchedAt = new Date().toISOString().slice(0, 10);
  const jobId = process.env.AGENT_SYNC_JOB_ID?.trim();
  const candidateFile = process.env.AGENT_SYNC_IMAGE_CANDIDATE_FILE?.trim();
  const captureValue = process.env.AGENT_SYNC_IMAGE_CAPTURE_ASINS;
  const asins = captureValue !== undefined
    ? imageRemarkCaptureScope(process.env.REMARK_ASINS === undefined ? null : analysisAsins,
      captureValue.split(",").map(item => item.trim()).filter(Boolean), {
        jobId, candidateFile, listingFile: process.env.AGENT_SYNC_LISTING_STAGE_FILE,
        listingHash: process.env.AGENT_SYNC_LISTING_STAGE_HASH,
      })
    : analysisAsins;
  const dispatch = new Set(analysisAsins);
  if (candidateFile && (!jobId || !process.env.AGENT_SYNC_LISTING_STAGE_FILE ||
      !/^[a-f0-9]{64}$/.test(process.env.AGENT_SYNC_LISTING_STAGE_HASH ?? ""))) {
    throw new Error("Image candidate requires a scoped persisted listing");
  }
  const listing = process.env.AGENT_SYNC_LISTING_STAGE_FILE
    ? readListingInputFile(process.env.AGENT_SYNC_LISTING_STAGE_FILE, jobId, asins, process.env.AGENT_SYNC_LISTING_STAGE_HASH)
    : readCachedDataExport(listingPath, "sorftimeListingContentData");
  const existing = readCachedDataExport(outPath, "listingImageRemarks");
  const existingMeta = readCachedDataExport(outPath, "listingImageRemarksMeta");
  const remarks = { ...existing };
  const hasOpenAI = hasOpenAiKey();
  const force = isForceRefresh();
  const explicitImageAction = ["refresh", "analyze"].includes(process.env.AGENT_SYNC_IMAGE_ACTION);

  if (!hasOpenAI) {
    console.log("[warn] 未设置 OPENAI_API_KEY（可写在 .env / .env.local / data/openai-api-key.txt），仅保留已有备注；新 ASIN 将显示「待分析」");
  }

  let analyzed = 0;
  let skipped = 0;
  let pendingWithoutKey = 0;
  let totalStaticImages = 0;
  let completedStaticImages = 0;
  const imageTasks = [];
  const remarkUpdates = [];
  const imageOutcomesByAsin = {};
  const persistCandidate = () => {
    if (!candidateFile) return;
    writeImageRemarkCandidate(candidateFile, createImageRemarkCandidate({
      jobId,
      listingContentHash: process.env.AGENT_SYNC_LISTING_STAGE_HASH,
      asins,
      listingByAsin: listing,
      remarksByAsin: remarks,
      outcomesByAsin: imageOutcomesByAsin,
    }));
  };
  const counts = {
    ready: 0,
    "upstream-empty": 0,
    timeout: 0,
    "connector-failed": 0,
  };

  for (const asin of asins) {
    const record = listing[asin];
    if (!record || record.status !== "ready" || !record.galleryImages?.length) {
      console.log(`[skip] ${asin} · 无 Listing 图册，请先 npm run listing:sync`);
      continue;
    }
    const previousUrls = existingMeta.imageUrlsByAsin?.[asin] ?? remarks[asin]?.map(remark => remark?.imageUrl);
    const previousRemarks = remarks[asin] ?? [];
    const alignedOutcomes = reconcileListingImageRemarks(previousUrls, record.galleryImages, existingMeta.imageOutcomesByAsin?.[asin]);
    remarks[asin] = reconcileListingImageRemarks(previousUrls, record.galleryImages, previousRemarks)
      .map((remark, slotIndex) => remark ? { ...remark, imageUrl: record.galleryImages[slotIndex] } : null);
    if (explicitImageAction && dispatch.has(asin)) {
      const aligned = Array.from({length:Math.max(previousRemarks.length,record.galleryImages.length)},(_,slotIndex)=>({asin,slotIndex,remark:remarks[asin][slotIndex] ?? null}));
      remarkUpdates.push(...aligned);
      await writeRemarksFile({ownedAsins:[asin],remarkUpdates:aligned,fetchedAt,listingByAsin:listing});
    }
    if (!force && !explicitImageAction && remarksComplete(asin, record, remarks)) {
      console.log(`[cache] ${asin} · 备注已齐全`);
      skipped += 1;
    }

    if (!remarks[asin]) remarks[asin] = [];
    const gallery = record.galleryImages;
    imageOutcomesByAsin[asin] = [];

    for (let slotIndex = 0; slotIndex < gallery.length; slotIndex += 1) {
      const url = gallery[slotIndex];
      if (isVideoThumb(url)) {
        imageOutcomesByAsin[asin][slotIndex] = null;
        if (!remarks[asin][slotIndex] && dispatch.has(asin)) {
          remarks[asin][slotIndex] = {
            remark: "Listing 视频位缩略图，非静态辅图分析范围。",
            imageUrl: url,
            image_types: ["其他"],
            confidence: "high",
          };
          remarkUpdates.push({ asin, slotIndex, remark: remarks[asin][slotIndex] });
        }
        continue;
      }
      totalStaticImages += 1;
      if (!dispatch.has(asin)) {
        const prior = alignedOutcomes[slotIndex];
        imageOutcomesByAsin[asin][slotIndex] = imageRemarkOutcome(prior?.status ??
          (remarks[asin][slotIndex]?.remark ? "ready" : "upstream-empty"), prior ?? {});
        completedStaticImages += 1;
        counts[imageOutcomesByAsin[asin][slotIndex].status] += 1;
        continue;
      }
      if (!force && !explicitImageAction && remarks[asin][slotIndex]?.remark) {
        imageOutcomesByAsin[asin][slotIndex] = imageRemarkOutcome("ready");
        completedStaticImages += 1;
        counts.ready += 1;
        continue;
      }
      const candidateOutcome = alignedOutcomes[slotIndex] ?? null;
      const priorOutcome = candidateOutcome?.status === "ready" && !remarks[asin][slotIndex]?.remark
        ? null
        : candidateOutcome;
      if (!shouldQueueImageRemarkSlot({ outcome: priorOutcome, force: force || explicitImageAction, jobId })) {
        imageOutcomesByAsin[asin][slotIndex] = imageRemarkOutcome(priorOutcome.status, {
          attemptJobId: priorOutcome.attemptJobId,
          diagnostic: priorOutcome.diagnostic,
        });
        completedStaticImages += 1;
        counts[priorOutcome.status] += 1;
        continue;
      }
      if (!hasOpenAI) {
        imageOutcomesByAsin[asin][slotIndex] = imageRemarkOutcome("connector-failed", { attemptJobId: jobId, diagnostic: {stage:"governance",httpStatus:null,errorClass:"governance",governanceCategory:"missing-key"} });
        completedStaticImages += 1;
        counts["connector-failed"] += 1;
        pendingWithoutKey += 1;
        continue;
      }

      imageTasks.push({ asin, slotIndex, url });
    }
  }

  const emitProgress = () => {
    console.log(`IMAGE_REMARK_PROGRESS ${JSON.stringify({
      completed: completedStaticImages,
      total: totalStaticImages,
      counts: { ...counts },
    })}`);
  };
  emitProgress();
  persistCandidate();

  const imageResults = await runImageRemarkQueue(imageTasks, async (task, { signal }) => {
    const result = await analyzeWithOpenAI(task.url, task.slotIndex, task.asin, signal);
    if (!result?.remark) return { status: "upstream-empty" };
    remarks[task.asin][task.slotIndex] = { ...result, imageUrl: task.url };
    remarkUpdates.push({ asin: task.asin, slotIndex: task.slotIndex, remark: remarks[task.asin][task.slotIndex] });
    analyzed += 1;
    return { status: "ready" };
  }, {
    jobId,
    onSettled: async ({ status, diagnostic }, index) => {
      const task = imageTasks[index];
      const durableRemark = status === "ready"
        ? remarks[task.asin]?.[task.slotIndex]
        : null;
      const settledOutcomes = [];
      settledOutcomes[task.slotIndex] = imageRemarkOutcome(status, { attemptJobId: jobId, diagnostic });
      imageOutcomesByAsin[task.asin][task.slotIndex] = settledOutcomes[task.slotIndex];
      await writeRemarksFile({
        ownedAsins: [task.asin],
        remarkUpdates: durableRemark?.remark
          ? [{ asin: task.asin, slotIndex: task.slotIndex, remark: durableRemark }]
          : [],
        fetchedAt,
        extraMeta: {
          imageOutcomesByAsin: { [task.asin]: settledOutcomes },
        },
        listingByAsin: listing,
      });
      persistCandidate();
      completedStaticImages += 1;
      counts[status] += 1;
      emitProgress();
    },
  });
  imageTasks.forEach((task, index) => {
    imageOutcomesByAsin[task.asin][task.slotIndex] = imageResults[index];
  });
  const currentAttemptComplete = asin => remarksComplete(asin, listing[asin], remarks) &&
    (imageOutcomesByAsin[asin] ?? []).filter(Boolean).every(outcome => outcome.status === "ready");
  const imageStatusByAsin = Object.fromEntries(asins.map(asin => [
    asin,
    aggregateImageRemarkResults(
      (imageOutcomesByAsin[asin] ?? []).filter(Boolean),
      {
        completeWithoutWork: currentAttemptComplete(asin),
        persistedComplete: currentAttemptComplete(asin),
      },
    ),
  ]));

  const pendingAsins = asins.filter(asin => {
    const record = listing[asin];
    return record?.status === "ready" && !currentAttemptComplete(asin);
  });
  if (analysisAsins.length) await writeRemarksFile({
    ownedAsins: analysisAsins,
    remarkUpdates,
    fetchedAt,
    extraMeta: {
      openaiConfigured: hasOpenAI,
      lastAnalyzedCount: analyzed,
      pendingAsins: pendingAsins.filter(asin => dispatch.has(asin)),
      pendingReason: !hasOpenAI && pendingAsins.length
        ? "missing_openai_key"
        : pendingAsins.length
          ? "analysis_incomplete"
          : null,
      imageStatusByAsin: Object.fromEntries(Object.entries(imageStatusByAsin).filter(([asin]) => dispatch.has(asin))),
      imageOutcomesByAsin: Object.fromEntries(Object.entries(imageOutcomesByAsin).filter(([asin]) => dispatch.has(asin))),
    },
    listingByAsin: listing,
  });
  persistCandidate();
  console.log(`[done] 新分析 ${analyzed} 张 · 跳过 ${skipped} 个 ASIN → app/listing-image-remarks.ts`);
  if (!hasOpenAI && pendingWithoutKey > 0) {
    console.error(`[error] ${pendingAsins.length} 个 ASIN 仍缺视觉备注：未配置 OPENAI_API_KEY`);
    process.exitCode = 2;
  } else if (pendingAsins.length) {
    console.error(`[error] ${pendingAsins.length} 个 ASIN 视觉备注未完成`);
    process.exitCode = 1;
  }
  console.log(`IMAGE_REMARK_OUTCOME ${JSON.stringify({
    status: pendingAsins.length ? "completed-with-gaps" : "completed",
  })}`);
}

main().catch(() => {
  console.log(`IMAGE_REMARK_OUTCOME ${JSON.stringify({ status: "integrity-failed" })}`);
  console.error("[error] 图片备注存储或完整性处理失败");
  process.exitCode = 1;
});
