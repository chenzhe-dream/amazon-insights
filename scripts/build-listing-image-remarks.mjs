import fs from "node:fs";
import path from "node:path";
import { hasCompleteImageRemarks } from "./lib/asin-data-status.mjs";
import { hasOpenAiKey, loadLocalEnv } from "./lib/local-env.mjs";
import {
  fetchImageRemarkWithTimeout,
  imageRemarkEndpoint,
  imageRemarkModel,
  imageRemarkRequestTimeoutMs,
  readImageRemarkProviderPayload,
} from "./lib/image-remark-request.mjs";
import { isForceRefresh, readCachedDataExport } from "./lib/sync-cache.mjs";

loadLocalEnv();

const root = path.resolve(import.meta.dirname, "..");
const catalogPath = path.join(root, "app", "competitor-data.ts");
const listingPath = path.join(root, "app", "sorftime-listing-content-data.ts");
const outPath = path.join(root, "app", "listing-image-remarks.ts");

const SKILL_PROMPT = `你是电商 Listing 主辅图视觉分析助手。分析这张商品图片，只依据画面中可见内容，返回 JSON：
{
  "image_types": ["1-3个中文类型"],
  "remark": "20-80字中文，展示方式+核心卖点",
  "confidence": "high|medium|low"
}
类型从以下选择：产品展示、核心卖点、功能展示、产品细节、结构展示、尺寸参数、使用场景、使用效果、人群展示、使用方法、折叠/收纳、灯光/视觉效果、多颜色/多款式、品牌形象、其他。
禁止编造图片中没有的信息。`;

function readCatalogAsins() {
  const source = fs.readFileSync(catalogPath, "utf8");
  return [...source.matchAll(/"asin":\s*"([A-Z0-9]{10})"/g)].map(match => match[1]);
}

function isVideoThumb(url) {
  return /play-button|PKplay-button/i.test(url);
}

function remarksComplete(asin, record, remarks) {
  return hasCompleteImageRemarks(record, remarks[asin]);
}

async function analyzeWithOpenAI(imageUrl, slotIndex, asin) {
  const apiKey = process.env.OPENAI_API_KEY?.trim();
  if (!apiKey) return null;

  const response = await fetchImageRemarkWithTimeout(fetch, imageRemarkEndpoint(), {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: imageRemarkModel(),
      temperature: 0.2,
      response_format: { type: "json_object" },
      messages: [
        {
          role: "user",
          content: [
            { type: "text", text: `${SKILL_PROMPT}\nASIN: ${asin} · 图片${slotIndex + 1}` },
            { type: "image_url", image_url: { url: imageUrl } },
          ],
        },
      ],
    }),
  }, imageRemarkRequestTimeoutMs());

  const payload = await readImageRemarkProviderPayload(response);
  const raw = payload.choices?.[0]?.message?.content;
  if (!raw) return null;
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new Error("Image analysis provider returned invalid remark JSON");
  }
  return {
    remark: String(parsed.remark ?? "").trim(),
    image_types: Array.isArray(parsed.image_types) ? parsed.image_types.map(String).slice(0, 3) : [],
    confidence: ["high", "medium", "low"].includes(parsed.confidence) ? parsed.confidence : "medium",
  };
}

function writeRemarksFile(remarks, fetchedAt, extraMeta = {}) {
  const body = `// Generated by scripts/build-listing-image-remarks.mjs — do not edit manually
export type ListingImageRemark = {
  remark: string;
  image_types: string[];
  confidence: "high" | "medium" | "low";
};

export const listingImageRemarksMeta = ${JSON.stringify(
    {
      source: "ecommerce-product-image-analysis",
      updatedAt: fetchedAt,
      syncCommand: "npm run image-remarks:sync",
      requiresOpenAI: "OPENAI_API_KEY",
      ...extraMeta,
    },
    null,
    2,
  )} as const;

/** 按 ASIN 索引，数组下标 0 = 图片1（主图），1 = 图片2（辅图）… */
export const listingImageRemarks: Record<string, ListingImageRemark[]> = ${JSON.stringify(remarks, null, 2)};

export function getListingImageRemark(asin: string, slotIndex: number): ListingImageRemark | null {
  return listingImageRemarks[asin]?.[slotIndex] ?? null;
}
`;
  fs.writeFileSync(outPath, body, "utf8");
}

async function main() {
  const asins =
    process.env.REMARK_ASINS?.split(",")
      .map(item => item.trim())
      .filter(Boolean) ?? readCatalogAsins();
  const fetchedAt = new Date().toISOString().slice(0, 10);
  const listing = readCachedDataExport(listingPath, "sorftimeListingContentData");
  const existing = readCachedDataExport(outPath, "listingImageRemarks");
  const remarks = { ...existing };
  const hasOpenAI = hasOpenAiKey();
  const force = isForceRefresh();

  if (!hasOpenAI) {
    console.log("[warn] 未设置 OPENAI_API_KEY（可写在 .env / .env.local / data/openai-api-key.txt），仅保留已有备注；新 ASIN 将显示「待分析」");
  }

  let analyzed = 0;
  let skipped = 0;
  let pendingWithoutKey = 0;

  for (const asin of asins) {
    const record = listing[asin];
    if (!record || record.status !== "ready" || !record.galleryImages?.length) {
      console.log(`[skip] ${asin} · 无 Listing 图册，请先 npm run listing:sync`);
      continue;
    }
    if (!force && remarksComplete(asin, record, remarks)) {
      console.log(`[cache] ${asin} · 备注已齐全`);
      skipped += 1;
      continue;
    }

    if (!remarks[asin]) remarks[asin] = [];
    const gallery = record.galleryImages;

    for (let slotIndex = 0; slotIndex < gallery.length; slotIndex += 1) {
      const url = gallery[slotIndex];
      if (isVideoThumb(url)) {
        if (!remarks[asin][slotIndex]) {
          remarks[asin][slotIndex] = {
            remark: "Listing 视频位缩略图，非静态辅图分析范围。",
            image_types: ["其他"],
            confidence: "high",
          };
        }
        continue;
      }
      if (!force && remarks[asin][slotIndex]?.remark) continue;
      if (!hasOpenAI) {
        pendingWithoutKey += 1;
        continue;
      }

      process.stdout.write(`[remark] ${asin} img${slotIndex + 1} ... `);
      try {
        const result = await analyzeWithOpenAI(url, slotIndex, asin);
        if (result?.remark) {
          remarks[asin][slotIndex] = result;
          analyzed += 1;
          console.log("ok");
        } else {
          console.log("empty");
        }
      } catch (error) {
        console.log(`error (${error instanceof Error ? error.message : String(error)})`);
      }
      await new Promise(resolve => setTimeout(resolve, 500));
    }
  }

  const pendingAsins = asins.filter(asin => {
    const record = listing[asin];
    return record?.status === "ready" && !remarksComplete(asin, record, remarks);
  });
  writeRemarksFile(remarks, fetchedAt, {
    openaiConfigured: hasOpenAI,
    lastAnalyzedCount: analyzed,
    pendingAsins,
    pendingReason: !hasOpenAI && pendingAsins.length
      ? "missing_openai_key"
      : pendingAsins.length
        ? "analysis_incomplete"
        : null,
  });
  console.log(`[done] 新分析 ${analyzed} 张 · 跳过 ${skipped} 个 ASIN → app/listing-image-remarks.ts`);
  if (!hasOpenAI && pendingWithoutKey > 0) {
    console.error(`[error] ${pendingAsins.length} 个 ASIN 仍缺视觉备注：未配置 OPENAI_API_KEY`);
    process.exitCode = 2;
  } else if (pendingAsins.length) {
    console.error(`[error] ${pendingAsins.length} 个 ASIN 视觉备注未完成`);
    process.exitCode = 1;
  }
}

main();
